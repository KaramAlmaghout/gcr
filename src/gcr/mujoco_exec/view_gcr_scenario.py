"""Open the full MuJoCo viewer for an exported GCR scenario.

Usage
-----
    cd <repository-root>
    python -m gcr view-scenario --scenario 7

The script reads the waypoint and obstacle CSVs generated by
``python -m gcr export-scenario-waypoints`` and launches MuJoCo's interactive
viewer.  Close the viewer window when you are done.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from gcr.paths import results_dir
from gcr.mujoco_exec.execute_plan import (
    DEFAULT_CABLE_SEGMENT_MULTIPLIER,
    YAW_MODE_CHOICES,
    YAW_MODE_SIMULTANEOUS,
    execute_waypoints_in_mujoco,
)
from gcr.sim.build_scene import CABLE_LENGTH, CABLE_NUM_SEGMENTS
from gcr.mujoco_exec.run_csv import parse_obstacles_csv, parse_waypoint_csv, parse_waypoint_metadata


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="View exported GCR waypoints in the full MuJoCo viewer.")
    parser.add_argument("--scenario", type=int, required=True, help="1-based scenario number to view.")
    parser.add_argument(
        "--waypoint-dir",
        default=None,
        help="Folder containing exported scenario CSVs. Default: results/gcr_waypoints",
    )
    parser.add_argument("--steps-per-waypoint", type=int, default=300)
    parser.add_argument(
        "--max-speed",
        type=float,
        default=0.10,
        help="Peak gripper speed cap [m/s]. Use 0 to rely only on steps-per-waypoint.",
    )
    parser.add_argument(
        "--yaw-mode",
        choices=YAW_MODE_CHOICES,
        default=YAW_MODE_SIMULTANEOUS,
        help="Waypoint yaw motion: interpolate with translation, or rotate first and then translate.",
    )
    parser.add_argument(
        "--cable-segments",
        type=int,
        default=None,
        help="Exact MuJoCo cable segment count. Overrides the metadata multiplier.",
    )
    parser.add_argument(
        "--cable-segment-multiplier",
        type=int,
        default=DEFAULT_CABLE_SEGMENT_MULTIPLIER,
        help=("Multiply exported planner segments for MuJoCo simulation "
              f"(default {DEFAULT_CABLE_SEGMENT_MULTIPLIER})."),
    )
    parser.add_argument("--no-obstacles", action="store_true", help="View robot/cable motion without obstacle geometry.")
    return parser.parse_args(argv)


def find_scenario_files(waypoint_dir: Path, scenario_number: int) -> tuple[Path, Path | None]:
    pattern = f"scenario_{scenario_number:02d}_*_waypoints.csv"
    matches = sorted(waypoint_dir.glob(pattern))
    if not matches:
        raise SystemExit(
            f"No waypoint CSV found for scenario {scenario_number} in {waypoint_dir}.\n"
            "Run: python -m gcr export-scenario-waypoints results/gcr_waypoints"
        )
    if len(matches) > 1:
        raise SystemExit(
            f"Several waypoint CSVs match scenario {scenario_number}:\n"
            + "\n".join(f"  {path}" for path in matches)
        )

    waypoint_csv = matches[0]
    obstacle_csv = waypoint_csv.with_name(waypoint_csv.name.replace("_waypoints.csv", "_obstacles.csv"))
    return waypoint_csv, obstacle_csv if obstacle_csv.exists() else None


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    waypoint_dir = Path(args.waypoint_dir) if args.waypoint_dir else results_dir() / "gcr_waypoints"
    waypoint_csv, obstacle_csv = find_scenario_files(waypoint_dir, args.scenario)

    targets = parse_waypoint_csv(waypoint_csv)
    metadata = parse_waypoint_metadata(waypoint_csv)
    cable_length = float(metadata.get("cable_length_m", CABLE_LENGTH))
    if args.cable_segment_multiplier < 1:
        raise SystemExit("--cable-segment-multiplier must be at least 1")
    metadata_segments = metadata.get("cable_segments")
    if args.cable_segments is not None:
        cable_segments = args.cable_segments
    elif metadata_segments is not None:
        cable_segments = int(metadata_segments) * args.cable_segment_multiplier
    else:
        cable_segments = CABLE_NUM_SEGMENTS
    cable_cstart_nodes = metadata.get("cable_cstart_xyz")
    if not isinstance(cable_cstart_nodes, np.ndarray):
        cable_cstart_nodes = None
    obstacles = []
    if obstacle_csv is not None and not args.no_obstacles:
        obstacles = parse_obstacles_csv(obstacle_csv)

    print(f"Opening MuJoCo viewer for scenario {args.scenario}.")
    print(f"  Waypoints: {waypoint_csv}")
    print(f"  Cable: length={cable_length:.6f} m, sim segments={cable_segments}, sim nodes={cable_segments + 1}")
    if obstacles:
        print(f"  Obstacles: {obstacle_csv}")
    else:
        print("  Obstacles: none")
    print("Close the MuJoCo viewer window to exit.\n")

    execute_waypoints_in_mujoco(
        targets,
        obstacles_3d=obstacles,
        steps_per_wp=args.steps_per_waypoint,
        max_gripper_speed=args.max_speed,
        cable_length=cable_length,
        cable_num_segments=cable_segments,
        cable_cstart_nodes=cable_cstart_nodes,
        yaw_mode=args.yaw_mode,
        use_viewer=True,
        save_video=False,
    )
    print("\nDone.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
